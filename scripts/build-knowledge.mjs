// Baut supabase/functions/azimut-chat/knowledge.md aus den Daten-JSONs (System-Kontext des Chat-Assistenten).
// Aufruf: node scripts/build-knowledge.mjs  (nach jeder Datenänderung neu ausführen und die Function neu deployen)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { buildTables, splitTokens, resolve, fmtValue, defaultFmt } from "../src/lib/story-core.ts";

const read = (p) => JSON.parse(readFileSync(new URL(`../public/data/${p}`, import.meta.url), "utf8"));
const story = read("story.json");
const flow = read("flow.json");
const sc = read("sites/sites_compare.json");
const db = read("isar/isar_data.json");
// Portfolio-Ketten liegen je Wendezeit vor; Verweise portfolio_chain:* meinen die Basis-Wendezeit.
const items = sc.portfolios.items.map((p) => ({ ...p, chain: (p.variants?.[p.default_turnaround] ?? p).chain }));
const tables = buildTables(db, { ...sc, portfolios: { ...sc.portfolios, items } });

const out = [];
const put = (s = "") => out.push(s);
const text = (s) => (s ? splitTokens(String(s), tables).map((p) => (typeof p === "string" ? p : p.text)).join("") : "");
const cut = (n) => (s) => (s && s.length > n ? `${s.slice(0, n).trimEnd()}…` : s);
const r1 = (x) => (typeof x === "number" && !Number.isInteger(x) ? Math.round(x * 1000) / 1000 : x);

/** Tabelle als Pipe-Zeilen; leere Spalten und Chat-Herkunft fallen weg. */
function table(name, rows, cols, filter = () => true, short = {}) {
  rows = rows.filter(filter).map((r) => ({ ...r, ...Object.fromEntries(Object.entries(short).map(([c, n]) => [c, cut(n)(r[c])])) }));
  if (!rows.length) return;
  put(`### ${name} (${rows.length} rows)`);
  put(cols.join(" | "));
  for (const r of rows) put(cols.map((c) => String(r1(r[c]) ?? "").replace(/\s+/g, " ").trim()).join(" | "));
  put();
}

/** Verschachteltes JSON als "pfad: wert"-Zeilen. */
function flat(obj, path = "", skip = []) {
  if (obj == null) return;
  if (typeof obj !== "object") return put(`${path}: ${r1(obj)}`);
  if (Array.isArray(obj) && obj.every((x) => x == null || typeof x !== "object")) return put(`${path}: ${obj.join(", ")}`);
  if (Array.isArray(obj) && obj.every((x) => Array.isArray(x) && x.every((y) => typeof y !== "object"))) {
    return put(`${path}: ${obj.map((x) => x.join(" / ")).join("; ")}`);
  }
  for (const [k, v] of Object.entries(obj)) if (!skip.includes(k) && !k.startsWith("_")) flat(v, path ? `${path}.${k}` : k, skip);
}

put("# Azimut knowledge base (Isar Aerospace case)");
put("Generated by scripts/build-knowledge.mjs from the data files behind https://ssco-hackathon-t2.github.io/azimut/. Data status: belegt = verified with source, abgeleitet = derived, annahme / team_annahme = assumption.");
put("Tool pages: home page chapters (World market /#einstieg, Orbits /#frage-1, Launch sites /#frage-2, Factory to launch /#frage-3, Recommendation /#empfehlung), deep dive per launch site /deepdive/<site_id>/, sources /belege/, analysis /analyse/, cost /kosten/, capital /kapital/, history /historie/, site comparison /standort/.");
put();

put("## 1. Story of the home page (numbers resolved)");
put(`Hero: ${story.hero.title} ${text(story.hero.lead)} Claim: ${story.hero.claim}`);
for (const ch of story.chapters) {
  put();
  put(`### Chapter ${ch.nav} (/#${ch.id}): ${text(ch.title)}`);
  if (ch.lead) put(text(ch.lead));
  for (const k of ch.kpis ?? []) {
    const v = resolve(tables, k.ref, k.of);
    const val = v ? fmtValue(v.value, k.format ?? defaultFmt(v), k.digits) : "[missing]";
    put(`- KPI: ${k.prefix ? `${k.prefix} ` : ""}${val}${k.suffix ?? ""} ${k.label}${k.note ? `. ${text(k.note)}` : ""}`);
  }
  for (const b of ch.blocks ?? []) if ("text" in b) put(`- ${b.title ? `${b.title}: ` : ""}${text(b.text)}`);
}
put();

put("## 2. Recommendation and interactive sections (flow.json; {placeholders} are filled live in the page)");
flat(flow.empfehlung, "recommendation");
// Karten-Texte je Startplatz wiederholen nur die Tabellen in Abschnitt 3 und 4.
flat(flow.startplaetze, "launch_sites", ["explorer", "plaetze"]);
flat(flow.deepdive, "deepdive", ["ui"]);
flat(flow.fabrik, "factory", ["dashboard"]);
flat(flow.orbits, "orbits", ["bahnen", "geschaeft"]);
flat(flow.weltmarkt, "world_market", ["pads", "orte", "home", "jahre", "texte"]);
flat(flow.hero, "hero");
put();

put("## 3. Launch site comparison (sites_compare.json, engine result)");
put(`Basis year ${sc.provenance.basis_year}, data status ${sc.provenance.data_status}. E0 = all payloads ${sc.e0_count}; union of openly addressable payloads (E2) over all six sites: ${sc.union_e2_count}.`);
table("sites", sc.sites, ["id", "label", "inc_min", "inc_max", "e1_share_count", "e2_count", "e2_share_count", "e2_share_mass", "missions_per_year", "e2_extra_vs_andoya", "isar_status", "isar_first_launch_year", "permitted_launches_per_year", "constraints", "business_cases", "source_ids"]);
put(`Q1 window: ${JSON.stringify(sc.q1)}`);
put(`E2 payloads reachable per site combination: ${Object.entries(sc.unions ?? {}).map(([k, v]) => `${k}=${v}`).join(", ")}`);
put();
put(`Site factors (score 1 to 5): ${sc.factors.factors.map((f) => `${f.id} = ${f.label} (${f.source})`).join("; ")}`);
table("site_factor_scores", sc.factors.values.map((v) => ({ ...v, score: Math.round(v.score * 10) / 10 })), ["site", "factor", "score", "status"]);
put("Portfolios: bottleneck chain from factory to winnable demand 2030, per turnaround days between launches on one pad (7, 30, 90).");
for (const p of sc.portfolios.items) {
  // Volle Kette nur für die Basis-Wendezeit, sonst nur das Ergebnis.
  for (const [days, v] of Object.entries(p.variants)) {
    const chain = days === p.default_turnaround ? `${v.chain.map((c) => `${c.label} ${r1(c.value)}`).join(" > ")}; ` : "";
    put(`- ${p.id} ${p.label}, turnaround ${days} d: ${chain}binding = ${v.binding}; expected successful ${r1(v.expected_successful)}; after a failure ${r1(v.after_failure)}`);
  }
}
for (const [k, m] of Object.entries(sc.portfolios.meta)) put(`- ${k}: low ${m.low}, base ${m.base}, high ${m.high} ${m.unit} (${m.status}). ${m.note ?? ""}`);
put();

put("## 4. Isar case database (isar_data.json)");
table("decisions", db.decisions, ["decided_on", "decision", "rationale"]);
table("scenarios", db.scenarios, ["name", "year", "launches_andoya", "launches_nova_scotia", "launches_kourou", "launches_total", "revenue_eur_m", "cost_per_launch_eur_m", "result_eur_m", "share_global_small_launches", "share_global_orbital_launches", "data_status", "note"]);
table("derived_kpis", db.derived_kpis, ["label", "value_low", "value_base", "value_high", "unit", "formula", "data_status"], undefined, { formula: 60 });
table("assumptions", db.assumptions, ["label", "value_low", "value_base", "value_high", "unit", "data_status", "rationale", "source_id"], undefined, { rationale: 90 });
table("launch_sites", db.launch_sites, ["id", "name", "operator", "country", "incl_min_deg", "incl_max_deg", "permitted_launches_per_year", "pads_built", "pads_planned", "isar_status", "isar_first_launch_year", "contract_terms", "fixed_fee_usd_m_per_year", "constraints", "realistic_isar_launches_min", "realistic_isar_launches_max", "data_status", "source_ids"]);
table("launch_vehicles", db.launch_vehicles, ["name", "company_id", "payload_leo_kg", "payload_sso_kg", "dev_status", "flights_total", "flights_success", "first_flight", "price_usd_m", "strength", "weakness", "source_ids"]);
table("funding_rounds", db.funding_rounds, ["company_id", "round_date", "round_name", "amount", "currency", "investors", "source_id"]);
table("backlog_items", db.backlog_items, ["customer", "item_type", "launches", "period", "value_eur_m", "item_status", "source_id", "note"]);
table("business_models", db.business_models, ["name", "ring_label", "customer_group", "market_size_usd_bn", "verdict", "rationale", "source_id"]);
table("demand_drivers", db.demand_drivers, ["driver", "direction", "segment", "description", "source_id"]);
table("cost_strategies", db.cost_strategies, ["lever", "description", "impact", "horizon", "evidence"]);
table("cost_curve", db.cost_curve, ["launches_per_year", "cumulative_unit", "variable_cost_eur_m", "fixed_cost_per_launch_eur_m", "cost_per_launch_eur_m", "cost_per_kg_sso_eur"]);
table("open_questions_and_risks (board_questions)", db.board_questions, ["role", "topic", "weakness", "question", "relevance"]);
table("corrections", db.corrections, ["claim", "correction", "source_id"]);
table("market_metrics", db.market_metrics, ["metric", "year", "value", "unit", "scope", "source_id"]);
// Wetter, Talent und Geopolitik sind Detail-Rohdaten der Standortfaktoren; die Scores stehen schon in Abschnitt 3.
table("facts", db.facts, ["entity_id", "topic", "statement", "source_id"], (f) => !["wetter", "talent", "geopolitik", "koordinate", "starts_je_startplatz", "geopolitik_index", "starts_zeitreihe", "marktwert_start", "neigung"].includes(f.topic), { statement: 160 });
// Nur Quellen, auf die oben verwiesen wird; Titel und Domain reichen zum Zitieren, die vollen Links stehen auf /belege/.
const cited = new Set(out.join("\n").match(/\bsrc_[a-z0-9_]+/g));
put("Full links of all sources: /belege/.");
table("sources", db.sources.map((s) => ({ ...s, site: s.url.replace(/^https?:\/\/(www\.)?/, "").split("/")[0] })), ["id", "title", "site"], (s) => cited.has(s.id), { title: 80 });

const md = out.join("\n");
const dir = new URL("../supabase/functions/azimut-chat/", import.meta.url);
mkdirSync(dir, { recursive: true });
writeFileSync(new URL("knowledge.md", dir), md);
console.log(`knowledge.md: ${md.length} chars, ~${Math.round(md.length / 3.6)} tokens`);
